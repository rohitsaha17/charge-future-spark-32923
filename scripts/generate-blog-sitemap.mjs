#!/usr/bin/env node
/**
 * Regenerate public/sitemap-blog.xml from the published blog posts in
 * Supabase. Run automatically before every production build via the
 * `prebuild` script in package.json — every Lovable deploy ships the
 * freshest blog URL list without anyone touching XML.
 *
 * Fails open: if Supabase env vars are missing or the request errors,
 * writes an empty (but valid) sitemap and exits 0. The page-level
 * sitemap and the rest of the build are unaffected.
 *
 * To run manually: `node scripts/generate-blog-sitemap.mjs`
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const OUT_FILE = resolve(ROOT, "public/sitemap-blog.xml");
const SITE_URL = "https://www.apluscharge.com";

const loadEnv = () => {
  const merged = { ...process.env };
  const envPath = resolve(ROOT, ".env");
  if (existsSync(envPath)) {
    const raw = readFileSync(envPath, "utf8");
    for (const line of raw.split("\n")) {
      const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*"?([^"]*)"?\s*$/i);
      if (m && merged[m[1]] === undefined) merged[m[1]] = m[2];
    }
  }
  return merged;
};

const writeSitemap = (entries) => {
  const lines = [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<!-- Auto-generated by scripts/generate-blog-sitemap.mjs at build time.`,
    `     Do not edit by hand — changes will be overwritten on next build. -->`,
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"`,
    `        xmlns:xhtml="http://www.w3.org/1999/xhtml"`,
    `        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">`,
  ];

  for (const e of entries) {
    const loc = `${SITE_URL}/blog/${e.slug}`;
    lines.push(`  <url>`);
    lines.push(`    <loc>${loc}</loc>`);
    if (e.updated_at) lines.push(`    <lastmod>${e.updated_at.slice(0, 10)}</lastmod>`);
    lines.push(`    <changefreq>monthly</changefreq>`);
    lines.push(`    <priority>0.6</priority>`);
    lines.push(`    <xhtml:link rel="alternate" hreflang="en"        href="${loc}" />`);
    lines.push(`    <xhtml:link rel="alternate" hreflang="en-IN"     href="${loc}" />`);
    lines.push(`    <xhtml:link rel="alternate" hreflang="x-default" href="${loc}" />`);
    if (e.featured_image) {
      lines.push(`    <image:image>`);
      lines.push(`      <image:loc>${e.featured_image}</image:loc>`);
      lines.push(`      <image:title>${escapeXml(e.title)}</image:title>`);
      lines.push(`    </image:image>`);
    }
    lines.push(`  </url>`);
  }

  lines.push(`</urlset>`);
  writeFileSync(OUT_FILE, lines.join("\n"), "utf8");
};

const escapeXml = (s) =>
  String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");

const main = async () => {
  const env = loadEnv();
  const SUPABASE_URL =
    env.VITE_SUPABASE_URL || env.SUPABASE_URL || "";
  const SUPABASE_KEY =
    env.VITE_SUPABASE_PUBLISHABLE_KEY ||
    env.SUPABASE_PUBLISHABLE_KEY ||
    env.SUPABASE_ANON_KEY ||
    "";

  if (!SUPABASE_URL || !SUPABASE_KEY) {
    console.warn("[sitemap-blog] Supabase env not configured — writing empty sitemap.");
    writeSitemap([]);
    process.exit(0);
  }

  const url =
    `${SUPABASE_URL}/rest/v1/blog_posts` +
    `?status=eq.published` +
    `&select=slug,title,updated_at,published_at,featured_image` +
    `&order=published_at.desc`;

  try {
    const res = await fetch(url, {
      headers: {
        apikey: SUPABASE_KEY,
        Authorization: `Bearer ${SUPABASE_KEY}`,
      },
    });
    if (!res.ok) {
      console.warn(
        `[sitemap-blog] Supabase responded ${res.status} — writing empty sitemap.`
      );
      writeSitemap([]);
      process.exit(0);
    }
    const rows = await res.json();
    const entries = (Array.isArray(rows) ? rows : []).filter((r) => r && r.slug);
    // Use published_at as lastmod if updated_at is missing
    for (const e of entries) e.updated_at = e.updated_at || e.published_at;
    writeSitemap(entries);
    console.log(`[sitemap-blog] Wrote ${entries.length} blog URLs to sitemap-blog.xml`);
  } catch (err) {
    console.warn("[sitemap-blog] Fetch failed:", err.message);
    writeSitemap([]);
    process.exit(0);
  }
};

main();
